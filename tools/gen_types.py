r"""Write LuaLS type annotations from the RTTI catalog, so an editor completes the whole game API.

    python gen_types.py                  # reads _cache\catalog\rtti.json, writes lua\types\w3.lua
    python gen_types.py --game "<game>"  # reads <game>\bin\x64_dx12\tw3se\catalog\rtti.json (the console command
                                         # `catalog` writes it), writes <game>\bin\x64_dx12\tw3se\lua\types\w3.lua
    python gen_types.py --vanilla "<game>"   # leaves out what installed mods added: script functions, methods and
                                             # fields whose name the game's own scripts (content\content0\scripts)
                                             # do not have

Open tw3se\lua in VS Code with the Lua extension (sumneko/LuaLS); it then completes w3.player() as a
W3PlayerWitcher with every field and method, each typed. One file with every class, enum and global function.
"""
import sys, os, json, glob, re

HERE = os.path.dirname(os.path.abspath(__file__))
IN = os.path.join(HERE, "..", "_cache", "catalog", "rtti.json")
OUT = os.path.join(HERE, "..", "lua", "types", "w3.lua")
if "--game" in sys.argv:
    _tw = os.path.join(sys.argv[sys.argv.index("--game") + 1], "bin", "x64_dx12", "tw3se")
    IN = os.path.join(_tw, "catalog", "rtti.json")
    OUT = os.path.join(_tw, "lua", "types", "w3.lua")

PRIM = {"Int8": "integer", "Uint8": "integer", "Int16": "integer", "Uint16": "integer", "Int32": "integer",
        "Uint32": "integer", "Int64": "integer", "Uint64": "integer", "Float": "number", "Double": "number",
        "Bool": "boolean", "String": "string", "CName": "string"}


def luatype(t, enums):
    """An engine type name -> a LuaLS type."""
    if not t:
        return "any"
    if t in PRIM:
        return PRIM[t]
    if t in enums:
        return "string"  # enums read/write as their value name
    if t.startswith("handle:") or t.startswith("ptr:") or t.startswith("soft:"):
        return luatype(t.split(":", 1)[1], enums)
    if t.startswith("array:"):
        return luatype(t.split(",", 2)[2], enums) + "[]"
    if t.startswith("map:"):
        return "table"
    if t.startswith("static:") or t.startswith("[") or t.startswith("map"):
        return "table"
    return t  # a class: use its name (declared as a @class below), or "any" if unknown


def ident(name):
    return name if name.replace("_", "").isalnum() and not name[0].isdigit() else None


def vanilla_words(game):
    """Every identifier in the game's own scripts."""
    words = set()
    for path in glob.glob(os.path.join(game, "content", "content0", "scripts", "**", "*.ws"), recursive=True):
        with open(path, "rb") as f:
            raw = f.read()
        text = raw.decode("utf-16") if raw[:2] in (b"\xff\xfe", b"\xfe\xff") else raw.decode("utf-8", "replace")
        words.update(re.findall(r"[A-Za-z_]\w*", text))
    if not words:
        sys.exit("no scripts in " + os.path.join(game, "content", "content0", "scripts"))
    return words


def drop_mods(d, words):
    """Takes out what mods added: a script function or method (flag 0x1 = native) or a script field (0x40000)
    whose name the game's scripts do not have."""
    def own(f):
        return f["flags"] & 1 or (f["name"] in words and "@" not in f["name"])
    n = len(d["functions"])
    d["functions"] = [f for f in d["functions"] if own(f)]
    gone = n - len(d["functions"])
    for t in d["types"]:
        if t["kind"] != 2:
            continue
        n = len(t["methods"]) + len(t["props"])
        t["methods"] = [m for m in t["methods"] if own(m)]
        t["props"] = [p for p in t["props"] if not p["flags"] & 0x40000 or p["name"] in words]
        gone += n - len(t["methods"]) - len(t["props"])
    print(f"{gone} entries of mods left out")


def main():
    with open(IN, encoding="utf-8") as f:
        d = json.load(f)
    if "--vanilla" in sys.argv:
        drop_mods(d, vanilla_words(sys.argv[sys.argv.index("--vanilla") + 1]))
    classes = {t["name"]: t for t in d["types"] if t["kind"] == 2}
    enums = {t["name"] for t in d["types"] if t["kind"] == 1}
    known = set(classes) | enums | set(PRIM)
    out = ["-- Generated by tools/gen_types.py from the RTTI catalog. Do not edit by hand.",
           "-- LuaLS annotations for the game's classes, enums and global functions.", "---@meta", ""]

    def ty(t):
        r = luatype(t, enums)
        base = r[:-2] if r.endswith("[]") else r
        if base not in known and base not in ("any", "integer", "number", "boolean", "string", "table"):
            return "any" + ("[]" if r.endswith("[]") else "")
        return r

    for name in sorted(classes):
        c = classes[name]
        parent = c.get("parent")
        hdr = "---@class " + name + (" : " + parent if parent and parent in classes else "")
        out.append(hdr)
        seen = set()
        for p in c["props"]:
            fn = ident(p["name"])
            if fn and fn not in seen:
                seen.add(fn)
                out.append("---@field " + fn + " " + ty(p["type"]))
        out.append("local " + name + " = {}")
        for m in c["methods"]:
            mn = ident(m["name"])
            if not mn:
                continue
            params = []
            for i, p in enumerate(m["params"]):
                pn = ident(p["name"]) or ("arg" + str(i + 1))
                params.append(pn)
                out.append("---@param " + pn + " " + ty(p["type"]))
            if m.get("ret"):
                out.append("---@return " + ty(m["ret"]))
            out.append("function " + name + ":" + mn + "(" + ", ".join(params) + ") end")
        out.append("")

    # global functions
    for fdef in sorted(d["functions"], key=lambda f: f["name"]):
        fn = ident(fdef["name"])
        if not fn:
            continue
        params = []
        for i, p in enumerate(fdef["params"]):
            pn = ident(p["name"]) or ("arg" + str(i + 1))
            params.append(pn)
            out.append("---@param " + pn + " " + ty(p["type"]))
        if fdef.get("ret"):
            out.append("---@return " + ty(fdef["ret"]))
        out.append("function " + fn + "(" + ", ".join(params) + ") end")

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print(f"{len(classes)} classes, {len(enums)} enums, {sum(1 for _ in d['functions'])} globals -> {OUT}")
    print(f"{os.path.getsize(OUT) // 1024} KB")


if __name__ == "__main__":
    main()
